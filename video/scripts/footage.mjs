// Builds src/footage.ts from the recorded clips' frames.json files
// (public/footage/<clip>/), so scenes can pick the frame for any moment.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const dir = new URL("../public/footage/", import.meta.url).pathname;
const clips = {};
for (const name of readdirSync(dir)) {
  const file = join(dir, name, "frames.json");
  if (!existsSync(file)) continue;
  const { width, height, duration, frames, marks } = JSON.parse(readFileSync(file, "utf8"));
  // Frame files are numbered in order, so only the times are kept.
  clips[name] = { width, height, duration, times: frames.map((f) => f.t), marks };
}
writeFileSync(
  new URL("../src/footage.ts", import.meta.url),
  `// Generated by scripts/footage.mjs from public/footage/*/frames.json.\nexport type Clip = { width: number; height: number; duration: number; times: number[]; marks: { label: string; t: number }[] };\nexport const FOOTAGE: Record<string, Clip> = ${JSON.stringify(clips)};\n`,
);
console.log(Object.entries(clips).map(([k, v]) => `${k}: ${v.times.length} frames, ${v.duration} s`).join("\n"));
